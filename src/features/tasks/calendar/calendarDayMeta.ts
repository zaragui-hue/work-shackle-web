export function getPublicHolidayName(dateKey: string): string | null {
  return CHINA_PUBLIC_HOLIDAYS[dateKey] ?? null;
}

export function isWeekend(date: Date): boolean {
  const weekday = date.getDay();
  return weekday === 0 || weekday === 6;
}

export function formatCalendarCellAriaLabel(input: {
  dateLabel: string;
  taskCount: number;
  busyLevel: BusyLevel;
  holidayName: string | null;
  isWeekend: boolean;
  isCurrentMonth: boolean;
}): string {
  if (!input.isCurrentMonth) {
    return input.dateLabel;
  }

  const parts = [input.dateLabel];

  if (input.holidayName) {
    parts.push(`节假日：${input.holidayName}`);
  } else if (input.isWeekend) {
    parts.push("周末");
  }

  if (input.taskCount > 0) {
    parts.push(formatTaskCountLabel(input.taskCount));
    parts.push(formatBusyStateLabel(input.busyLevel));
  }

  return parts.join("，");
}
